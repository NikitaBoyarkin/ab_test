# -*- coding: utf-8 -*-
"""Pins on the numbers the README publishes.

Every figure in README.md's "Result" (lines 28-32) and "Headline results"
(lines 45-62) sections is recomputed here through the same code paths the
pipeline uses, at the *default* DGP -- no re-implemented statistics, no
re-derived formulas. Source of truth for the values: `outputs/report.md`
regenerated by `uv run python scripts/run_full_pipeline.py`.

The default DGP is deterministic given its seed (`generate_data()` defaults to
seed=7), so the tolerances below are one unit in the last digit the README
prints -- not a statistical margin. A changed seed, effect, or estimator moves
these by whole percentage points and fails loudly.
"""

import sys
from pathlib import Path

import pandas as pd
import pytest

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "scripts"))

import run_full_pipeline as rfp
import sample_size as ss

ROOT = Path(__file__).resolve().parent.parent
README = ROOT / "README.md"
SAMPLE_CSV = ROOT / "data" / "experiment_sample.csv"

ABS_4DP = 1e-4  # README prints 4 decimals, e.g. 0.0499, 0.8376
ABS_5DP = 1e-5  # README prints 5 decimals, e.g. 0.00360, +0.00512
ABS_PCT = 1e-3  # README prints percentages to one decimal, e.g. 17.7%


@pytest.fixture(scope="module")
def default_run():
    """The README's experiment: 21 days x 2,000 users/day at `generate_data()` defaults."""
    df = rfp.generate_data()
    return df, rfp.run_pipeline(df)


def test_dgp_is_42000_users_over_21_days(default_run):
    # README.md:46 "(42,000 users, 21 days, A = 20,979 / B = 21,021)"
    df, _ = default_run
    assert len(df) == 42_000
    assert df["day"].nunique() == 21
    assert int((df["treat"] == 0).sum()) == 20_979
    assert int((df["treat"] == 1).sum()) == 21_021


def test_srm_split_is_clean(default_run):
    # README.md:30,51 "A 20,979 / B 21,021, p = 0.8376"
    _, res = default_run
    srm = res["srm"]
    assert [int(n) for n in srm["observed"]] == [20_979, 21_021]
    assert srm["p_value"] == pytest.approx(0.8376, abs=ABS_4DP)
    assert not srm["srm_detected"]


def test_cuped_variance_reduction(default_run):
    # README.md:28,52 "17.7% ... (SE 0.00360 -> 0.00327)"
    _, res = default_run
    cup = res["cuped"]
    assert cup["se_naive"] == pytest.approx(0.00360, abs=ABS_5DP)
    assert cup["se_cuped"] == pytest.approx(0.00327, abs=ABS_5DP)
    assert cup["var_reduction"] == pytest.approx(0.177, abs=ABS_PCT)


def test_delta_method_ctr_lift(default_run):
    # README.md:29,53 "0.0499 -> 0.0550, +0.00512, p < 0.0001"
    _, res = default_run
    ratio = res["ratio"]
    assert ratio["ratio_a"] == pytest.approx(0.0499, abs=ABS_4DP)
    assert ratio["ratio_b"] == pytest.approx(0.0550, abs=ABS_4DP)
    assert ratio["diff"] == pytest.approx(0.00512, abs=ABS_5DP)
    assert ratio["p_value"] < 1e-4
    assert ratio["significant"]


def test_segments_null_after_bh_correction(default_run):
    # README.md:31,54 "mobile +0.0015, desktop -0.0001, tablet -0.0128 ...
    # (all p_adj > 0.32)", tablet p_adj = 0.3224
    _, res = default_run
    seg = res["segments"].set_index("segment")
    assert seg.loc["mobile", "ate"] == pytest.approx(0.0015, abs=ABS_4DP)
    assert seg.loc["desktop", "ate"] == pytest.approx(-0.0001, abs=ABS_4DP)
    assert seg.loc["tablet", "ate"] == pytest.approx(-0.0128, abs=ABS_4DP)
    assert not seg["sig"].any()
    assert (seg["p_adj"] > 0.32).all()
    # The tightest p_adj is tablet's -- it is what "all p_adj > 0.32" rests on.
    assert seg.loc["tablet", "p_adj"] == pytest.approx(0.3224, abs=ABS_4DP)


def test_novelty_row(default_run):
    # README.md:55 "treat x day +0.00065, p = 0.2714"
    _, res = default_run
    trend = res["trend"]
    assert trend["inter_coef"] == pytest.approx(0.00065, abs=ABS_5DP)
    assert trend["p_value"] == pytest.approx(0.2714, abs=ABS_4DP)


def test_sample_size_closed_forms():
    # README.md:32,180 "sample-size closed forms (3024 / 3839 / 393)"
    # Same known-answer fixture as tests/test_sample_size.py::test_known_answers.
    assert ss.two_proportion(0.10, 0.02) == 3024
    assert ss.two_proportion(0.10, 0.02, one_tail=False) == 3839
    assert ss.two_mean(effect_size=0.2, sd=1.0) == 393


def test_committed_csv_fixture_numbers():
    # README.md:58-62: the CSV is a 600-user demo in the same schema; on it the
    # pipeline gives CTR +0.37pp (p = 0.207) and CUPED removes 14.9% of variance.
    df = pd.read_csv(SAMPLE_CSV)
    assert len(df) == 600
    res = rfp.run_pipeline(df)
    ratio, cup = res["ratio"], res["cuped"]
    assert ratio["diff"] == pytest.approx(0.00373, abs=ABS_5DP)
    assert ratio["p_value"] == pytest.approx(0.2073, abs=ABS_4DP)
    assert cup["var_reduction"] == pytest.approx(0.149, abs=ABS_PCT)


@pytest.mark.parametrize(
    "published",
    [
        "17.7%",
        "0.00360 → 0.00327",
        "0.0499 → 0.0550",
        "+0.00512",
        "0.8376",
        "20,979 / B 21,021",
        "42,000",
        "3024 / 3839 / 393",
        "+0.37pp",
        "14.9%",
    ],
)
def test_readme_still_publishes_the_pinned_numbers(published):
    assert published in README.read_text(encoding="utf-8")
